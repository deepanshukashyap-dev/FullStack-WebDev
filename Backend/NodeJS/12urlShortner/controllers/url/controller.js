const urlModel = require("../../models/url");
const shortid = require("shortid");//to generate short ids,package

async function handleGenerateNewShortURL(req, res) {//request = post
  const body = req.body; //getting JSON body from the request

  if (!body.url) {//if url not present in body(from the user)
    return res.status(400).json({ error: "URL is required" });
  }

  const shortId = shortid(8); //generating shortId of length 8

  await urlModel.create({
    shortId: shortId, //generated by shortid nodeJs package
    redirectUrl: body.url, //from the user 
    visitHistory: [],//initially empty
    createdBy:req.user._id,//storing the user id who created this short url
  });
  
  return res.render("home",{ id:shortId });//for showing the generated shortId on home page
}

async function handleRedirectShortId(req, res) {//redirecting shortId to original url
  const shortId = req.params.shortId;
  const entry = await urlModel.findOneAndUpdate(//find the shortId in db and update its visit history
    { shortId },
    { $push: { visitHistory: { timestamp: Date.now() } } } 
  );
    res.redirect(entry.redirectUrl);//redirect to original url
}

async function handleShowAnalytics(req, res) {
  const shortId = req.params.shortId;
  const user = await urlModel.findOne({ shortId });
  res.json({
    clicks: user.visitHistory.length,
    analytics: user.visitHistory,
  });
}

module.exports = {
  handleGenerateNewShortURL,
  handleShowAnalytics,
  handleRedirectShortId,
};
